// Regenerates template-data.js from ../index.html and ../js/main.js.
// Run this (node generate-template-data.js) whenever those two files change,
// so the configurator keeps working standalone (no server/fetch needed).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const html = fs.readFileSync(path.join(__dirname, "..", "index.html"), "utf-8");
const js = fs.readFileSync(path.join(__dirname, "..", "js", "main.js"), "utf-8");

const out = `// Auto-generated by generate-template-data.js — do not edit by hand.
// Source of truth: ../index.html and ../js/main.js
const TEMPLATE_HTML = ${JSON.stringify(html)};
const TEMPLATE_JS = ${JSON.stringify(js)};
`;

fs.writeFileSync(path.join(__dirname, "template-data.js"), out);
console.log("template-data.js aktualisiert.");
